export function getTranslatedGenre(genreNameOrSlug, lang = 'en') {
  if (!genreNameOrSlug) return '';
  const key = String(genreNameOrSlug).toLowerCase().trim();
  const slug = GENRE_NAME_TO_SLUG[key] || key;
  const langDict = genreTranslations[lang] || genreTranslations.en;
  return langDict[slug] || genreTranslations.en[slug] || genreNameOrSlug;
}

