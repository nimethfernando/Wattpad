export function getLocalizedStory(story, lang = 'en') {
  if (!story) return story;
  if (!lang || lang === 'en') return story;
  const trans = storyTranslations[lang]?.[story.id] || storyTranslations[lang]?.[story.slug];
  if (!trans) return story;
  return {
    ...story,
    title: trans.title || story.title,
    description: trans.description || story.description
  };
}
