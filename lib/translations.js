export function getTranslatedDay(dayName, lang = 'en') {
  if (!dayName) return '';
  const dayIndexMap = {
    "mon": 0, "m": 0, "monday": 0,
    "tue": 1, "t": 1, "tuesday": 1,
    "wed": 2, "w": 2, "wednesday": 2,
    "thu": 3, "thursday": 3,
    "fri": 4, "f": 4, "friday": 4,
    "sat": 5, "s": 5, "saturday": 5,
    "sun": 6, "sunday": 6
  };
  const key = String(dayName).toLowerCase().trim();
  const idx = dayIndexMap[key];
  if (idx !== undefined && dayTranslations[lang]) {
    return dayTranslations[lang].days[idx];
  }
  return dayName;
}

