import Razorpay from 'razorpay';
import crypto from 'crypto';

/**
 * Server-side Razorpay Client for Production Payment Processing
 * Reads credentials securely from environment variables:
 * - RAZORPAY_KEY_ID (e.g. rzp_live_... or rzp_test_...)
 * - RAZORPAY_KEY_SECRET
 * - RAZORPAY_WEBHOOK_SECRET
 */

const keyId = process.env.RAZORPAY_KEY_ID || process.env.NEXT_PUBLIC_RAZORPAY_KEY_ID;
const keySecret = process.env.RAZORPAY_KEY_SECRET;
const webhookSecret = process.env.RAZORPAY_WEBHOOK_SECRET;

export const razorpay = (keyId && keySecret)
  ? new Razorpay({
      key_id: keyId,
      key_secret: keySecret,
      headers: {
        'User-Agent': 'AvoraLibrary/1.0.0 (Next.js Razorpay Production Engine)'
      }
    })
  : null;

export const isRazorpayConfigured = () => Boolean(keyId && keySecret);

export const getRazorpayKeyId = () => keyId || process.env.NEXT_PUBLIC_RAZORPAY_KEY_ID || '';

/**
 * Cryptographically verifies Razorpay payment signature (HMAC SHA-256)
 * generated by the client checkout modal.
 * 
 * Formula: HMAC_SHA256(order_id + "|" + payment_id, secret) === signature
 * 
 * @param {Object} params
 * @param {string} params.order_id
 * @param {string} params.payment_id
 * @param {string} params.signature
 * @returns {boolean}
 */
export function verifyPaymentSignature({ order_id, payment_id, signature }) {
  if (!keySecret) {
    throw new Error('Razorpay Key Secret is not configured on the server.');
  }
  if (!order_id || !payment_id || !signature) {
    return false;
  }

  const generatedSignature = crypto
    .createHmac('sha256', keySecret)
    .update(`${order_id}|${payment_id}`)
    .digest('hex');

  // Constant-time buffer comparison to prevent timing attacks
  const generatedBuf = Buffer.from(generatedSignature, 'utf-8');
  const signatureBuf = Buffer.from(signature, 'utf-8');

  if (generatedBuf.length !== signatureBuf.length) {
    return false;
  }

  return crypto.timingSafeEqual(generatedBuf, signatureBuf);
}

/**
 * Cryptographically verifies Razorpay Webhook signature (HMAC SHA-256)
 * 
 * @param {string} rawBodyString - Raw JSON payload received in webhook request
 * @param {string} webhookSignature - Value from 'x-razorpay-signature' header
 * @returns {boolean}
 */
export function verifyWebhookSignature(rawBodyString, webhookSignature) {
  const secret = webhookSecret || keySecret;
  if (!secret) {
    throw new Error('Razorpay Webhook Secret is not configured on the server.');
  }
  if (!rawBodyString || !webhookSignature) {
    return false;
  }

  const expectedSignature = crypto
    .createHmac('sha256', secret)
    .update(rawBodyString)
    .digest('hex');

  const expectedBuf = Buffer.from(expectedSignature, 'utf-8');
  const actualBuf = Buffer.from(webhookSignature, 'utf-8');

  if (expectedBuf.length !== actualBuf.length) {
    return false;
  }

  return crypto.timingSafeEqual(expectedBuf, actualBuf);
}

